#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
const text = fs.readFileSync('docs/release-artifacts.md', 'utf8');
const provenanceDocs = fs.readFileSync('docs/security/release-provenance.md', 'utf8');
const stage = fs.readFileSync('scripts/stage-release.js', 'utf8');
const schema = JSON.parse(fs.readFileSync('schemas/release-provenance-v1.schema.json', 'utf8'));
const packageJson = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const attributes = fs.readFileSync('.gitattributes', 'utf8');
for (const token of ['npm pack', 'SHA-256', 'CycloneDX', 'sign', 'verification', 'RELEASE_OWNER_APPROVED=true', 'revoke', 'roll back']) assert(text.toLowerCase().includes(token.toLowerCase()), `artifact flow must define ${token}`);
for (const token of ['immutable source', 'clean checkout', 'two clean builds', 'signature', 'owner']) assert(provenanceDocs.toLowerCase().includes(token), `provenance flow must define ${token}`);
assert(fs.existsSync('docs/security/sbom.json'), 'SBOM must be available');
assert(fs.existsSync('docs/migrations.md'), 'rollback documentation must be available');
assert.equal(packageJson.scripts['release:stage'], 'node scripts/stage-release.js');
assert(attributes.includes('* text=auto eol=lf'), 'release text must use normalized LF line endings');
assert.equal(schema.properties.schemaVersion.const, 1);
for (const key of ['package', 'source', 'subjects', 'build', 'reproducibility', 'releaseReadiness', 'signature', 'approval', 'publication']) assert(schema.required.includes(key), `provenance schema must require ${key}`);
for (const token of ['git', 'worktree', 'npm pack', '--ignore-scripts', 'firstBytes.equals(secondBytes)', 'SBOM.cdx.json', 'OWNER_DECISION_PACKET.md', 'PROVENANCE.json', 'SHA256SUMS']) assert(stage.includes(token), `release staging must include ${token}`);
assert(!stage.includes('npm publish'), 'release staging must never publish');
assert(!stage.includes("['tag'"), 'release staging must never create a tag');
console.log('release artifact contracts passed');
